import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))

import check  # noqa: E402


class RepoFixture:
    """Builds a throwaway repository tree for one test."""

    def __init__(self):
        self._dir = tempfile.TemporaryDirectory()
        self.root = Path(self._dir.name)

    def write(self, relative: str, content: str) -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def cleanup(self):
        self._dir.cleanup()


class CheckTestCase(unittest.TestCase):
    def setUp(self):
        self.repo = RepoFixture()
        self.addCleanup(self.repo.cleanup)


class DocsParityTest(CheckTestCase):
    def test_reports_pages_missing_in_either_language(self):
        self.repo.write("docs/en/index.md", "# Index\n")
        self.repo.write("docs/en/install.md", "# Install\n")
        self.repo.write("docs/fr/index.md", "# Index\n")
        self.repo.write("docs/fr/extra.md", "# Extra\n")
        problems = check.check_docs_parity(self.repo.root)
        self.assertEqual(
            problems,
            ["docs/fr/install.md is missing (exists in docs/en)", "docs/en/extra.md is missing (exists in docs/fr)"],
        )

    def test_passes_when_trees_match(self):
        self.repo.write("docs/en/a/b.md", "x")
        self.repo.write("docs/fr/a/b.md", "x")
        self.assertEqual(check.check_docs_parity(self.repo.root), [])


class LinksTest(CheckTestCase):
    def test_reports_broken_files_and_anchors(self):
        self.repo.write("docs/en/target.md", "# Real Heading\n\n## Second `code` part\n")
        self.repo.write(
            "docs/en/index.md",
            "[ok](target.md#real-heading) [ok2](target.md#second-code-part) [web](https://example.com)\n"
            "[bad](missing.md) [badanchor](target.md#nope) [self](#local)\n\n## Local\n",
        )
        problems = check.check_links(self.repo.root)
        self.assertEqual(len(problems), 2, problems)
        self.assertIn("broken link to 'missing.md'", problems[0])
        self.assertIn("missing anchor '#nope'", problems[1])

    def test_ignores_links_inside_code_fences(self):
        self.repo.write("README.md", "```\n[x](nowhere.md)\n```\n")
        self.assertEqual(check.check_links(self.repo.root), [])

    def test_duplicate_headings_get_numbered_anchors(self):
        self.assertEqual(check.heading_anchors("# A\n## A\n"), {"a", "a-1"})


