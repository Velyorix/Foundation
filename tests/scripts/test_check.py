class VersionsTest(CheckTestCase):
    def write_versions(self, manifest: str, module: str, changelog: str | None):
        self.repo.write("package/Package.toml", f'[meta]\n    version = "{manifest}"\n')
        self.repo.write("package/Shared/foundation/version.lua", f'return {{ PRODUCT = "{module}" }}\n')
        if changelog is not None:
            self.repo.write("CHANGELOG.md", changelog)

    def test_passes_when_consistent(self):
        self.write_versions("1.2.3", "1.2.3", "## [Unreleased]\n")
        self.assertEqual(check.check_versions(self.repo.root), [])

    def test_reports_mismatch(self):
        self.write_versions("1.2.3", "1.2.4", "## [Unreleased]\n")
        self.assertIn("version mismatch", check.check_versions(self.repo.root)[0])

    def test_reports_missing_changelog_section(self):
        self.write_versions("1.2.3", "1.2.3", "## [1.0.0]\n")
        self.assertIn("neither an [Unreleased]", check.check_versions(self.repo.root)[0])

    def test_rejects_non_core_semver(self):
        self.write_versions("1.2.3-dev", "1.2.3-dev", "## [Unreleased]\n")
        self.assertIn("is not X.Y.Z", check.check_versions(self.repo.root)[0])


class StripLuaCommentsTest(unittest.TestCase):
    def test_keeps_strings_containing_dashes(self):
        self.assertEqual(check.strip_lua_comments('local a = "--x" -- note'), 'local a = "--x" ')

    def test_handles_escaped_quotes(self):
        self.assertEqual(check.strip_lua_comments('local a = "\\"--" -- c'), 'local a = "\\"--" ')

    def test_code_only_blanks_string_contents(self):
        self.assertEqual(check.lua_code_only('f("io.open", \'x\') -- io.'), "f(\"\", '') ")


