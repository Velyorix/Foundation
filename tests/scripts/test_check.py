class SecretsTest(CheckTestCase):
    def test_flags_known_secret_formats(self):
        aws_key = "AKIA" + "ABCDEFGHIJKLMNOP"
        github_token = "ghp_" + "a" * 36
        key_header = "-----BEGIN " + "PRIVATE KEY-----"
        self.repo.write("notes.txt", f"{aws_key}\n{github_token}\n{key_header}\n")
        self.assertEqual(len(check.check_secrets(self.repo.root)), 3)

    def test_skips_ignored_directories(self):
        self.repo.write(".tmp/leak.txt", "ghp_" + "b" * 36 + "\n")
        self.assertEqual(check.check_secrets(self.repo.root), [])


